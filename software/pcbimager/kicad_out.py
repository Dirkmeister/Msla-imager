"""Write a minimal KiCad 7 board (.kicad_pcb) from top-view geometry (mm, y up, origin at the
panel centre). Used for test-vehicle artwork (T-SW-1, S-3, S-5) so it runs through the real
KiCad export path. KiCad's internal y points down; boards are placed around ORIGIN.
"""
import uuid

from .geom import Track, Flash, Region

ORIGIN = (150.0, 100.0)   # KiCad position of the panel centre, mm


def _k(p):
    return f"{ORIGIN[0] + p[0]:.6f} {ORIGIN[1] - p[1]:.6f}"


def _u():
    return str(uuid.uuid4())


class Board:
    def __init__(self):
        self.items = []

    def track(self, t, layer):
        self.items.append(f'  (segment (start {_k(t.p0)}) (end {_k(t.p1)}) (width {t.w:.6f}) '
                          f'(layer "{layer}") (net 0) (tstamp {_u()}))')

    def smd_pad(self, f, layer, ref="P"):
        shape = {"rect": "rect", "circle": "circle", "obround": "oval"}[f.shape]
        mask = "F.Mask" if layer == "F.Cu" else "B.Mask"
        self.items.append(
            f'  (footprint "imager:{ref}" (layer "{layer}") (tstamp {_u()}) (at {_k(f.c)})\n'
            f'    (attr smd board_only exclude_from_pos_files exclude_from_bom)\n'
            f'    (pad "1" smd {shape} (at 0 0) (size {f.w:.6f} {f.h:.6f}) (layers "{layer}" "{mask}") '
            f'(tstamp {_u()}))\n  )')

    def tht_pad(self, c, pad_d, drill_d, ref="H"):
        self.items.append(
            f'  (footprint "imager:{ref}" (layer "F.Cu") (tstamp {_u()}) (at {_k(c)})\n'
            f'    (attr through_hole board_only exclude_from_pos_files exclude_from_bom)\n'
            f'    (pad "1" thru_hole circle (at 0 0) (size {pad_d:.6f} {pad_d:.6f}) (drill {drill_d:.6f}) '
            f'(layers "*.Cu" "*.Mask") (tstamp {_u()}))\n  )')

    def region(self, r, layer):
        for ring in r.rings:
            pts = " ".join(f"(xy {_k(p)})" for p in ring)
            self.items.append(f'  (gr_poly (pts {pts}) (stroke (width 0) (type solid)) (fill solid) '
                              f'(layer "{layer}") (tstamp {_u()}))')

    def layer(self, lay, layer):
        for p in lay:
            if isinstance(p, Track):
                if not p.dark:
                    raise ValueError("clear tracks have no KiCad equivalent here")
                self.track(p, layer)
            elif isinstance(p, Flash):
                self.smd_pad(p, layer)
            elif isinstance(p, Region):
                self.region(p, layer)

    def text(self, s, c, h, w, layer, mirror=False):
        just = " (justify mirror)" if mirror else ""
        self.items.append(f'  (gr_text "{s}" (at {_k(c)}) (layer "{layer}") (tstamp {_u()})\n'
                          f'    (effects (font (size {h:.6f} {h:.6f}) (thickness {w:.6f})){just}))')

    def outline_rect(self, w, h):
        a, b = (-w / 2, h / 2), (w / 2, -h / 2)
        self.items.append(f'  (gr_rect (start {_k(a)}) (end {_k(b)}) (stroke (width 0.1) (type solid)) '
                          f'(fill none) (layer "Edge.Cuts") (tstamp {_u()}))')

    def write(self, path, title="imager test vehicle"):
        head = f"""(kicad_pcb (version 20221018) (generator pcbnew)
  (general (thickness 1.6))
  (paper "A4")
  (title_block (title "{title}") (comment 1 "generated by pcb-imager, -DK"))
  (layers
    (0 "F.Cu" signal)
    (31 "B.Cu" signal)
    (36 "B.SilkS" user "B.Silkscreen")
    (37 "F.SilkS" user "F.Silkscreen")
    (38 "B.Mask" user)
    (39 "F.Mask" user)
    (44 "Edge.Cuts" user)
  )
  (setup (pad_to_mask_clearance 0))
  (net 0 "")
"""
        with open(path, "w") as f:
            f.write(head + "\n".join(self.items) + "\n)\n")
